-- Durable, tenant-scoped automation events for knowledge follow-up and CRM
-- stage transitions. Apply only after reviewing the target Supabase schema.

begin;

create table if not exists public.automation_events (
    id bigint generated by default as identity primary key,
    company_id bigint not null references public.companies(id) on delete cascade,
    chatbot_id bigint not null references public.chatbots(id) on delete cascade,
    event_type text not null,
    status text not null default 'queued',
    idempotency_key text not null,
    payload jsonb not null default '{}'::jsonb,
    result jsonb,
    error_message text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint automation_events_type_check check (
        event_type in ('knowledge_document_follow_up', 'crm_stage_transition')
    ),
    constraint automation_events_status_check check (
        status in ('queued', 'running', 'completed', 'failed', 'blocked')
    ),
    constraint automation_events_idempotency_key_check check (
        length(idempotency_key) between 1 and 200
    )
);

create unique index if not exists automation_events_company_key_idx
    on public.automation_events(company_id, idempotency_key);

create index if not exists automation_events_company_chatbot_created_idx
    on public.automation_events(company_id, chatbot_id, created_at desc);

create index if not exists automation_events_status_idx
    on public.automation_events(status, created_at);

alter table public.automation_events enable row level security;

revoke all privileges on table public.automation_events
    from public, anon, authenticated;

grant select, insert, update on table public.automation_events to service_role;
grant usage, select on sequence public.automation_events_id_seq to service_role;

comment on table public.automation_events is
    'Service-role managed, tenant-scoped automation events. Payloads must be redacted and bounded.';

commit;
