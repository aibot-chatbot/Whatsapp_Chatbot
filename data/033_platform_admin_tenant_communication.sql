CREATE OR REPLACE FUNCTION public.create_platform_support_case_reply(
    p_case_id BIGINT,
    p_platform_admin_user_id BIGINT,
    p_redacted_body TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path TO pg_catalog
AS $function$
DECLARE
    v_case public.platform_support_cases%ROWTYPE;
    v_request public.tenant_support_requests%ROWTYPE;
    v_reply public.tenant_support_replies%ROWTYPE;
    v_event_id BIGINT;
    v_notification public.tenant_support_reply_notifications%ROWTYPE;
    v_body TEXT;
    v_now TIMESTAMPTZ := pg_catalog.now();
BEGIN
    PERFORM public.require_active_platform_admin_mapping(p_platform_admin_user_id);
    IF p_case_id IS NULL OR p_case_id <= 0 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Invalid support case ID';
    END IF;

    v_body := pg_catalog.btrim(p_redacted_body);
    IF v_body IS NULL OR pg_catalog.char_length(v_body) < 1 OR pg_catalog.char_length(v_body) > 4000 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Invalid tenant-visible reply';
    END IF;

    SELECT * INTO v_case
    FROM public.platform_support_cases
    WHERE id = p_case_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Support case not found';
    END IF;

    SELECT * INTO v_request
    FROM public.tenant_support_requests
    WHERE converted_platform_support_case_id = p_case_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING
            ERRCODE = 'P0002',
            MESSAGE = 'Converted tenant support request not found';
    END IF;
    IF v_request.company_id <> v_case.company_id THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            MESSAGE = 'Tenant support request and case company mismatch';
    END IF;

    INSERT INTO public.tenant_support_replies (
        request_id,
        platform_support_case_id,
        company_id,
        author_type,
        author_platform_admin_user_id,
        redacted_body,
        visibility_status,
        created_at
    ) VALUES (
        v_request.id,
        p_case_id,
        v_case.company_id,
        'platform_admin',
        p_platform_admin_user_id,
        v_body,
        'visible',
        v_now
    )
    RETURNING * INTO v_reply;

    UPDATE public.platform_support_cases
    SET updated_at = v_now
    WHERE id = p_case_id;

    INSERT INTO public.platform_support_case_events (
        case_id,
        event_type,
        actor_platform_admin_user_id,
        tenant_support_reply_id,
        created_at
    ) VALUES (
        p_case_id,
        'tenant_reply_created',
        p_platform_admin_user_id,
        v_reply.id,
        v_now
    )
    RETURNING id INTO v_event_id;

    INSERT INTO public.platform_admin_audit_events (
        platform_admin_user_id, action, resource_type, resource_id, metadata, created_at
    ) VALUES (
        p_platform_admin_user_id,
        'platform_admin.support_case.reply.create',
        'tenant_support_replies',
        v_reply.id::TEXT,
        pg_catalog.jsonb_build_object(
            'endpoint', '/api/platform-admin/support-cases/<case_id>/replies',
            'http_method', 'POST',
            'outcome', 'success',
            'case_id', p_case_id,
            'request_id', v_request.id,
            'company_id', v_case.company_id,
            'reply_id', v_reply.id,
            'notification_channel', 'in_app',
            'delivery_status', 'pending'
        ),
        v_now
    );

    INSERT INTO public.tenant_support_reply_notifications (
        reply_id,
        request_id,
        platform_support_case_id,
        company_id,
        channel,
        status,
        idempotency_key,
        created_at,
        updated_at
    ) VALUES (
        v_reply.id,
        v_request.id,
        p_case_id,
        v_case.company_id,
        'in_app',
        'pending',
        'tenant_support_reply:' || v_reply.id::TEXT || ':in_app',
        v_now,
        v_now
    )
    RETURNING * INTO v_notification;

    RETURN pg_catalog.jsonb_build_object(
        'reply', pg_catalog.to_jsonb(v_reply),
        'case', (
            SELECT pg_catalog.to_jsonb(c)
            FROM public.platform_support_cases AS c
            WHERE c.id = p_case_id
        ),
        'event', (
            SELECT pg_catalog.to_jsonb(e)
            FROM public.platform_support_case_events AS e
            WHERE e.id = v_event_id
        ),
        'notification', pg_catalog.to_jsonb(v_notification)
    );
END;
$function$;

