CREATE TABLE IF NOT EXISTS public.tenant_support_replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL
        REFERENCES public.tenant_support_requests(id) ON DELETE RESTRICT,
    platform_support_case_id BIGINT NOT NULL
        REFERENCES public.platform_support_cases(id) ON DELETE RESTRICT,
    company_id BIGINT NOT NULL
        REFERENCES public.companies(id) ON DELETE RESTRICT,
    author_type TEXT NOT NULL,
    author_platform_admin_user_id BIGINT NULL
        REFERENCES public.platform_admin_users(id) ON DELETE RESTRICT,
    redacted_body TEXT NOT NULL,
    visibility_status TEXT NOT NULL DEFAULT 'visible',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT tenant_support_replies_author_type_check
        CHECK (author_type IN ('platform_admin')),
    CONSTRAINT tenant_support_replies_author_consistency_check
        CHECK (
            author_type = 'platform_admin'
            AND author_platform_admin_user_id IS NOT NULL
        ),
    CONSTRAINT tenant_support_replies_body_length_check
        CHECK (char_length(redacted_body) BETWEEN 1 AND 4000),
    CONSTRAINT tenant_support_replies_visibility_status_check
        CHECK (visibility_status = 'visible')
);

CREATE INDEX IF NOT EXISTS ix_tenant_support_replies_request_created
    ON public.tenant_support_replies (request_id, created_at ASC, id ASC);
CREATE INDEX IF NOT EXISTS ix_tenant_support_replies_case_created
    ON public.tenant_support_replies (platform_support_case_id, created_at ASC, id ASC);
CREATE INDEX IF NOT EXISTS ix_tenant_support_replies_company_created
    ON public.tenant_support_replies (company_id, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.tenant_support_reply_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reply_id BIGINT NOT NULL
        REFERENCES public.tenant_support_replies(id) ON DELETE RESTRICT,
    request_id BIGINT NOT NULL
        REFERENCES public.tenant_support_requests(id) ON DELETE RESTRICT,
    platform_support_case_id BIGINT NOT NULL
        REFERENCES public.platform_support_cases(id) ON DELETE RESTRICT,
    company_id BIGINT NOT NULL
        REFERENCES public.companies(id) ON DELETE RESTRICT,
    channel TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    idempotency_key TEXT NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    last_attempt_at TIMESTAMPTZ NULL,
    delivered_at TIMESTAMPTZ NULL,
    failure_code TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT tenant_support_reply_notifications_channel_check
        CHECK (channel IN ('in_app')),
    CONSTRAINT tenant_support_reply_notifications_status_check
        CHECK (status IN ('pending', 'sent', 'failed')),
    CONSTRAINT tenant_support_reply_notifications_attempt_count_check
        CHECK (attempt_count >= 0),
    CONSTRAINT tenant_support_reply_notifications_failure_code_check
        CHECK (failure_code IS NULL OR char_length(failure_code) BETWEEN 1 AND 80),
    CONSTRAINT tenant_support_reply_notifications_delivery_check
        CHECK (
            (status = 'sent' AND delivered_at IS NOT NULL AND failure_code IS NULL)
            OR (status = 'failed' AND delivered_at IS NULL AND failure_code IS NOT NULL)
            OR (status = 'pending' AND delivered_at IS NULL AND failure_code IS NULL)
        )
);

