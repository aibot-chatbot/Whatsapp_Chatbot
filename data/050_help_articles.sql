-- Global platform help articles and one-vote-per-tenant helpfulness feedback.
-- Articles are platform content, not tenant content: there is no company_id on
-- help_articles and no tenant filter on the read path. Feedback is the tenant
-- scoped half, and its company_id is derived from the JWT on the server, never
-- sent by the browser. Apply only after reviewing the target Supabase schema.

begin;

create table if not exists public.help_articles (
    id bigint generated by default as identity primary key,
    category text not null,
    title text not null,
    body text not null,
    slug text not null,
    is_published boolean not null default false,
    sort_order integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint help_articles_category_check check (
        category in (
            'technical', 'account', 'chatbot', 'integration',
            'billing_question', 'ai_credits', 'other'
        )
    ),
    constraint help_articles_title_check check (
        length(title) between 1 and 200
    ),
    constraint help_articles_slug_check check (
        slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and length(slug) between 1 and 200
    ),
    constraint help_articles_body_check check (
        length(body) between 1 and 8000
    )
);

create unique index if not exists help_articles_slug_idx
    on public.help_articles(slug);

create index if not exists help_articles_published_sort_idx
    on public.help_articles(is_published, sort_order, id);

create index if not exists help_articles_category_sort_idx
    on public.help_articles(category, sort_order, id);

create table if not exists public.help_article_feedback (
    id bigint generated by default as identity primary key,
    article_id bigint not null references public.help_articles(id) on delete cascade,
    company_id bigint not null references public.companies(id) on delete cascade,
    was_helpful boolean not null,
    created_at timestamptz not null default now()
);

create unique index if not exists help_article_feedback_article_company_idx
    on public.help_article_feedback(article_id, company_id);

create index if not exists help_article_feedback_article_idx
    on public.help_article_feedback(article_id, was_helpful);

alter table public.help_articles enable row level security;
alter table public.help_article_feedback enable row level security;

revoke all privileges on table public.help_articles
    from public, anon, authenticated;

revoke all privileges on table public.help_article_feedback
    from public, anon, authenticated;

grant select, insert, update, delete on table public.help_articles to service_role;
grant usage, select on sequence public.help_articles_id_seq to service_role;

grant select, insert, update on table public.help_article_feedback to service_role;
grant usage, select on sequence public.help_article_feedback_id_seq to service_role;

comment on table public.help_articles is
    'Service-role managed global help articles. Bodies are plain prose rendered with textContent; only published rows are ever served to tenants.';

comment on table public.help_article_feedback is
    'Service-role managed helpfulness votes, one per tenant per article. company_id is derived from the JWT, never accepted from a client payload.';

