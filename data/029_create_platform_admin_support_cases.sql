CREATE TABLE IF NOT EXISTS public.platform_support_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL
        REFERENCES public.companies(id) ON DELETE RESTRICT,
    created_by_platform_admin_user_id BIGINT NOT NULL
        REFERENCES public.platform_admin_users(id) ON DELETE RESTRICT,
    assigned_platform_admin_user_id BIGINT NULL
        REFERENCES public.platform_admin_users(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'open',
    priority TEXT NOT NULL DEFAULT 'normal',
    title TEXT NOT NULL,
    redacted_summary TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    closed_at TIMESTAMPTZ NULL,
    CONSTRAINT platform_support_cases_status_check
        CHECK (status IN ('open', 'in_progress', 'resolved', 'closed')),
    CONSTRAINT platform_support_cases_priority_check
        CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
    CONSTRAINT platform_support_cases_title_length_check
        CHECK (char_length(title) BETWEEN 1 AND 160),
    CONSTRAINT platform_support_cases_summary_length_check
        CHECK (char_length(redacted_summary) BETWEEN 1 AND 2000),
    CONSTRAINT platform_support_cases_closed_at_check
        CHECK ((status = 'closed') = (closed_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.platform_support_case_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL
        REFERENCES public.platform_support_cases(id) ON DELETE RESTRICT,
    event_type TEXT NOT NULL,
    actor_platform_admin_user_id BIGINT NOT NULL
        REFERENCES public.platform_admin_users(id) ON DELETE RESTRICT,
    old_status TEXT NULL,
    new_status TEXT NULL,
    old_priority TEXT NULL,
    new_priority TEXT NULL,
    redacted_note TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT platform_support_case_events_type_check
        CHECK (event_type IN ('created', 'note_added', 'status_changed', 'priority_changed')),
    CONSTRAINT platform_support_case_events_status_check
        CHECK (
            (old_status IS NULL OR old_status IN ('open', 'in_progress', 'resolved', 'closed'))
            AND (new_status IS NULL OR new_status IN ('open', 'in_progress', 'resolved', 'closed'))
        ),
    CONSTRAINT platform_support_case_events_priority_check
        CHECK (
            (old_priority IS NULL OR old_priority IN ('low', 'normal', 'high', 'urgent'))
            AND (new_priority IS NULL OR new_priority IN ('low', 'normal', 'high', 'urgent'))
        ),
    CONSTRAINT platform_support_case_events_note_length_check
        CHECK (redacted_note IS NULL OR char_length(redacted_note) BETWEEN 1 AND 2000)
);

CREATE INDEX IF NOT EXISTS ix_platform_support_cases_company_updated
    ON public.platform_support_cases (company_id, updated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_platform_support_cases_status_priority
    ON public.platform_support_cases (status, priority, updated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_platform_support_case_events_case_created
    ON public.platform_support_case_events (case_id, created_at ASC, id ASC);

CREATE OR REPLACE FUNCTION public.reject_platform_support_case_event_mutation()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path TO pg_catalog
AS $function$
BEGIN
    RAISE EXCEPTION USING
        ERRCODE = '55000',
        MESSAGE = 'platform_support_case_events is append-only';
END;
$function$;

DROP TRIGGER IF EXISTS platform_support_case_events_reject_mutation
    ON public.platform_support_case_events;

CREATE TRIGGER platform_support_case_events_reject_mutation
    BEFORE UPDATE OR DELETE
    ON public.platform_support_case_events
    FOR EACH ROW
    EXECUTE FUNCTION public.reject_platform_support_case_event_mutation();

ALTER TABLE public.platform_support_cases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.platform_support_case_events ENABLE ROW LEVEL SECURITY;

