    ON public.platform_support_cases;
CREATE POLICY platform_support_cases_service_update
    ON public.platform_support_cases FOR UPDATE TO service_role USING (TRUE) WITH CHECK (TRUE);

DROP POLICY IF EXISTS platform_support_case_events_service_select
    ON public.platform_support_case_events;
CREATE POLICY platform_support_case_events_service_select
    ON public.platform_support_case_events FOR SELECT TO service_role USING (TRUE);

DROP POLICY IF EXISTS platform_support_case_events_service_insert
