CREATE OR REPLACE FUNCTION public.require_platform_staff_access(
    p_actor BIGINT, p_module TEXT DEFAULT NULL, p_super_only BOOLEAN DEFAULT FALSE
)
RETURNS VOID LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog
AS $function$
DECLARE v_staff public.platform_admin_users%ROWTYPE;
BEGIN
    SELECT m.* INTO v_staff FROM public.platform_admin_users m
    JOIN public.users u ON u.id = m.user_id AND u.status = 'active'
    WHERE m.id = p_actor AND m.is_active = TRUE FOR UPDATE OF m;
    IF NOT FOUND OR v_staff.platform_role IS NULL OR v_staff.platform_role NOT IN ('super_admin','admin') THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Configured active platform staff required';
    END IF;
    IF p_super_only AND v_staff.platform_role <> 'super_admin' THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Super Admin required';
    END IF;
    IF p_module IS NOT NULL AND (p_module NOT IN ('billing','support','customers') OR
        (v_staff.platform_role <> 'super_admin' AND (v_staff.modules -> p_module) IS DISTINCT FROM 'true'::jsonb)) THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Staff module is not assigned';
    END IF;
END;
$function$;

-- New staff start with an explicit Admin role and no assigned modules.
CREATE OR REPLACE FUNCTION public.create_platform_admin_user_mapping(
    p_actor_platform_admin_user_id BIGINT,
    p_target_user_id BIGINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path TO pg_catalog
AS $function$
DECLARE
    v_actor public.platform_admin_users%ROWTYPE;
    v_target_user public.users%ROWTYPE;
    v_existing_mapping_id BIGINT;
    v_new_mapping public.platform_admin_users%ROWTYPE;
    v_audit public.platform_admin_audit_events%ROWTYPE;
    v_now TIMESTAMPTZ := pg_catalog.now();
BEGIN
    IF p_actor_platform_admin_user_id IS NULL OR p_actor_platform_admin_user_id <= 0 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Invalid platform-admin actor ID';
    END IF;
    IF p_target_user_id IS NULL OR p_target_user_id <= 0 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Invalid target user ID';
    END IF;

    LOCK TABLE public.platform_admin_users IN SHARE ROW EXCLUSIVE MODE;

    PERFORM public.require_platform_staff_access(p_actor_platform_admin_user_id, NULL, TRUE);

    SELECT * INTO v_actor
    FROM public.platform_admin_users
    WHERE id = p_actor_platform_admin_user_id
      AND is_active = TRUE
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Active platform-admin mapping is required';
    END IF;

    SELECT * INTO v_target_user
    FROM public.users
    WHERE id = p_target_user_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Target user not found';
    END IF;
    IF v_target_user.status IS DISTINCT FROM 'active' THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Target user must be active';
    END IF;
    IF v_target_user.company_id IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Target user must belong to a protected company';
    END IF;

    PERFORM 1
    FROM public.platform_admin_protected_companies
    WHERE company_id = v_target_user.company_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Target user must belong to a protected company';
    END IF;

    SELECT id INTO v_existing_mapping_id
    FROM public.platform_admin_users
    WHERE user_id = p_target_user_id
    FOR UPDATE;

    IF FOUND THEN
        RAISE EXCEPTION USING ERRCODE = '23505', MESSAGE = 'Platform-admin mapping already exists';
    END IF;

    INSERT INTO public.platform_admin_users (
        user_id,
        is_active,
        created_by_user_id,
        platform_role,
        modules
    ) VALUES (
        p_target_user_id,
        TRUE,
        v_actor.user_id,
        'admin',
        '{"billing":false,"support":false,"customers":false}'::jsonb
    )
    RETURNING * INTO v_new_mapping;

    INSERT INTO public.platform_admin_audit_events (
        platform_admin_user_id,
        action,
        resource_type,
        resource_id,
        metadata,
        created_at
    ) VALUES (
        p_actor_platform_admin_user_id,
        'platform_admin.user.create',
        'platform_admin_users',
        v_new_mapping.id::TEXT,
        pg_catalog.jsonb_build_object(
            'endpoint', '/api/platform-admin/platform-admin-users',
            'http_method', 'POST',
            'outcome', 'success',
            'target_platform_admin_user_id', v_new_mapping.id,
            'target_user_id', p_target_user_id,
            'old_is_active', NULL,
            'new_is_active', TRUE
        ),
        v_now
    )
    RETURNING * INTO v_audit;

    RETURN pg_catalog.jsonb_build_object(
        'platform_admin_user', pg_catalog.to_jsonb(v_new_mapping),
        'audit_event', pg_catalog.to_jsonb(v_audit)
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.set_platform_staff_access(
    p_actor_platform_admin_user_id BIGINT,
    p_target_platform_admin_user_id BIGINT,
    p_platform_role TEXT,
    p_modules JSONB,
    p_reason TEXT,
    p_is_active BOOLEAN DEFAULT NULL
)
RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog
AS $function$
DECLARE
    v_target public.platform_admin_users%ROWTYPE;
    v_old public.platform_admin_users%ROWTYPE;
    v_audit public.platform_admin_audit_events%ROWTYPE;
    v_role TEXT;
    v_active BOOLEAN;
    v_modules JSONB;
    v_action TEXT;
BEGIN
    IF p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 1 AND 2000 THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'A reason is required';
    END IF;
    -- Serializes every access/active-state change, including the legacy endpoint.
    LOCK TABLE public.platform_admin_users IN SHARE ROW EXCLUSIVE MODE;
    PERFORM public.require_platform_staff_access(p_actor_platform_admin_user_id, NULL, TRUE);
    SELECT * INTO v_old FROM public.platform_admin_users WHERE id = p_target_platform_admin_user_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Platform-admin mapping not found';
    END IF;
    v_role := coalesce(p_platform_role, v_old.platform_role);
    v_active := coalesce(p_is_active, v_old.is_active);
    v_modules := coalesce(p_modules, v_old.modules);
    IF v_role IS NULL OR v_role NOT IN ('super_admin','admin') OR v_modules IS NULL
       OR jsonb_typeof(v_modules) IS DISTINCT FROM 'object'
       OR NOT (v_modules ?& ARRAY['billing','support','customers'])
       OR v_modules - ARRAY['billing','support','customers'] <> '{}'::jsonb
       OR jsonb_typeof(v_modules->'billing') IS DISTINCT FROM 'boolean'
       OR jsonb_typeof(v_modules->'support') IS DISTINCT FROM 'boolean'
       OR jsonb_typeof(v_modules->'customers') IS DISTINCT FROM 'boolean' THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Invalid staff role or module grants';
    END IF;
    IF p_actor_platform_admin_user_id = p_target_platform_admin_user_id AND (NOT v_active OR v_role <> 'super_admin') THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Self-demotion is not allowed';
    END IF;
    IF v_old.is_active AND v_old.platform_role = 'super_admin' AND (NOT v_active OR v_role <> 'super_admin')
       AND NOT EXISTS (SELECT 1 FROM public.platform_admin_users m JOIN public.users u ON u.id = m.user_id
           WHERE m.id <> v_old.id AND m.is_active AND m.platform_role = 'super_admin' AND u.status = 'active') THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'At least one active Super Admin is required';
    END IF;
    IF v_active AND NOT EXISTS (SELECT 1 FROM public.users u
        JOIN public.platform_admin_protected_companies p ON p.company_id = u.company_id
        WHERE u.id = v_old.user_id AND u.status = 'active') THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Active staff must belong to a protected company';
    END IF;
    IF v_role = 'super_admin' THEN v_modules := '{"billing":true,"support":true,"customers":true}'::jsonb; END IF;
    UPDATE public.platform_admin_users SET platform_role = v_role, modules = v_modules,
        is_active = v_active, updated_at = now() WHERE id = v_old.id RETURNING * INTO v_target;
    v_action := CASE WHEN p_is_active IS NULL THEN 'platform_admin.user.access.update'
        WHEN p_is_active THEN 'platform_admin.user.activate' ELSE 'platform_admin.user.deactivate' END;
    INSERT INTO public.platform_admin_audit_events(platform_admin_user_id, action, resource_type, resource_id, metadata)
    VALUES (p_actor_platform_admin_user_id, v_action, 'platform_admin_users', v_target.id::text,
        jsonb_build_object('outcome','success','http_method','PATCH',
          'endpoint', CASE WHEN p_is_active IS NULL THEN '/api/platform-admin/platform-admin-users/<platform_admin_user_id>/access'
                          ELSE '/api/platform-admin/platform-admin-users/<platform_admin_user_id>/active' END,
          'target_platform_admin_user_id',v_target.id,'target_user_id',v_target.user_id,
          'old_is_active',v_old.is_active,'new_is_active',v_target.is_active,
          'old_platform_role',v_old.platform_role,'new_platform_role',v_role,
          'old_modules',v_old.modules,'new_modules',v_modules,'reason',btrim(p_reason))) RETURNING * INTO v_audit;
    RETURN jsonb_build_object('platform_admin_user',to_jsonb(v_target),'audit_event',to_jsonb(v_audit));
END;
$function$;

