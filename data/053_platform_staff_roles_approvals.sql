            AND modules ?& ARRAY['billing','support','customers']
            AND modules - ARRAY['billing','support','customers'] = '{}'::jsonb
            AND jsonb_typeof(modules->'billing') = 'boolean'
            AND jsonb_typeof(modules->'support') = 'boolean'
            AND jsonb_typeof(modules->'customers') = 'boolean'
        );
    END IF;
END;
