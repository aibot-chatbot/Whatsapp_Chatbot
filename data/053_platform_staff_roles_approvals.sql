CREATE OR REPLACE FUNCTION public.create_platform_approval_request(
    p_actor_platform_admin_user_id BIGINT, p_type TEXT, p_company_id BIGINT, p_summary TEXT, p_reason TEXT
)
RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog
AS $function$
DECLARE
    v_request public.platform_approval_requests%ROWTYPE;
    v_audit public.platform_admin_audit_events%ROWTYPE;
    v_module TEXT;
BEGIN
    v_module := CASE WHEN p_type IN ('refund','manual_payment','plan_change') THEN 'billing'
        WHEN p_type IN ('account_change','suspension') THEN 'customers'
        WHEN p_type = 'support_escalation' THEN 'support' END;
    IF v_module IS NULL OR p_summary IS NULL OR length(btrim(p_summary)) NOT BETWEEN 1 AND 240
       OR p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 1 AND 2000 THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='Invalid approval request';
    END IF;
    PERFORM public.require_platform_staff_access(p_actor_platform_admin_user_id, v_module, FALSE);
    PERFORM 1 FROM public.companies WHERE id = p_company_id;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Company not found'; END IF;
    INSERT INTO public.platform_approval_requests(type,company_id,requester_platform_admin_user_id,summary,reason)
        VALUES(p_type,p_company_id,p_actor_platform_admin_user_id,btrim(p_summary),btrim(p_reason)) RETURNING * INTO v_request;
    INSERT INTO public.platform_admin_audit_events(platform_admin_user_id,action,resource_type,resource_id,metadata)
        VALUES(p_actor_platform_admin_user_id,'platform_admin.approval.create','platform_approval_requests',v_request.id::text,
            jsonb_build_object('outcome','success','http_method','POST','endpoint','/api/platform-admin/approval-requests',
                               'company_id',p_company_id,'new_status','pending')) RETURNING * INTO v_audit;
    RETURN jsonb_build_object('request',to_jsonb(v_request),'audit_event',to_jsonb(v_audit));
END;
$function$;

CREATE OR REPLACE FUNCTION public.decide_platform_approval_request(
    p_actor_platform_admin_user_id BIGINT, p_request_id BIGINT, p_status TEXT, p_reason TEXT
)
RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog
AS $function$
DECLARE v_request public.platform_approval_requests%ROWTYPE; v_audit public.platform_admin_audit_events%ROWTYPE;
BEGIN
    PERFORM public.require_platform_staff_access(p_actor_platform_admin_user_id, NULL, TRUE);
    IF p_status IS NULL OR p_status NOT IN ('approved','rejected') OR p_reason IS NULL
       OR length(btrim(p_reason)) NOT BETWEEN 1 AND 2000 THEN
        RAISE EXCEPTION USING ERRCODE='22023', MESSAGE='A decision and reason are required';
    END IF;
    SELECT * INTO v_request FROM public.platform_approval_requests WHERE id = p_request_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='P0002', MESSAGE='Approval request not found'; END IF;
    IF v_request.status <> 'pending' THEN
        RAISE EXCEPTION USING ERRCODE='23505', MESSAGE='Approval request is already decided';
    END IF;
    UPDATE public.platform_approval_requests SET status = p_status, decision_reason = btrim(p_reason),
        reviewed_by_platform_admin_user_id = p_actor_platform_admin_user_id, reviewed_at = now(), updated_at = now()
        WHERE id = p_request_id RETURNING * INTO v_request;
    INSERT INTO public.platform_admin_audit_events(platform_admin_user_id,action,resource_type,resource_id,metadata)
        VALUES(p_actor_platform_admin_user_id,'platform_admin.approval.decide','platform_approval_requests',p_request_id::text,
            jsonb_build_object('outcome','success','http_method','POST',
                'endpoint','/api/platform-admin/approval-requests/<approval_id>/decision',
                'old_status','pending','new_status',p_status,'execution_status','not_executed')) RETURNING * INTO v_audit;
    RETURN jsonb_build_object('request',to_jsonb(v_request),'audit_event',to_jsonb(v_audit));
END;
$function$;

