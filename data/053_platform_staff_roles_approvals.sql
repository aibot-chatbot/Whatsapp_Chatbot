-- Tenant account writers must revoke staff access through the Super Admin path
-- before deactivating its underlying identity. Lock before user rows so mapping
-- creation (which locks the mapping table before users) cannot invert this order.
CREATE OR REPLACE FUNCTION public.protect_platform_staff_account_status()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path TO pg_catalog
AS $function$
BEGIN
    IF TG_LEVEL = 'STATEMENT' THEN
        -- ponytail: serialize account-status changes with staff grants; use a
        -- dedicated lifecycle lock if this low-volume operation becomes busy.
        LOCK TABLE public.platform_admin_users IN SHARE ROW EXCLUSIVE MODE;
        RETURN NULL;
    END IF;
    IF EXISTS (SELECT 1 FROM public.platform_admin_users
               WHERE user_id = OLD.id AND is_active) THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'platform_staff_account_protected';
    END IF;
    RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.protect_platform_staff_account_status() FROM PUBLIC, anon, authenticated, service_role;
DROP TRIGGER IF EXISTS platform_staff_status_lock ON public.users;
CREATE TRIGGER platform_staff_status_lock BEFORE UPDATE OF status ON public.users
    FOR EACH STATEMENT EXECUTE FUNCTION public.protect_platform_staff_account_status();
DROP TRIGGER IF EXISTS platform_staff_status_guard ON public.users;
CREATE TRIGGER platform_staff_status_guard BEFORE UPDATE OF status ON public.users
    FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status AND NEW.status IS DISTINCT FROM 'active')
    EXECUTE FUNCTION public.protect_platform_staff_account_status();

