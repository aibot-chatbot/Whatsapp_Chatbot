-- Help articles and tenant intake have separate 050/052 rollout requirements.
-- No identities are provisioned and no existing mapping is granted a role here.
-- Rollout: review/apply 053, then explicitly provision the designated initial Super
-- mapping in the protected company. Assign staff role/modules only to reviewed IDs.
-- Never infer role from an email or tenant role. Do not start by auto-promoting all
-- existing mappings. Subsequent staff can use the Super-only create/access APIs.
-- Existing NULL-role mappings fail closed until explicitly assigned by an operator.
BEGIN;

ALTER TABLE public.platform_admin_users
    ADD COLUMN IF NOT EXISTS platform_role TEXT,
    ADD COLUMN IF NOT EXISTS modules JSONB NOT NULL DEFAULT '{"billing":false,"support":false,"customers":false}'::jsonb;

