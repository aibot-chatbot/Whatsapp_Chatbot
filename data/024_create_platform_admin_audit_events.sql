-- 024_create_platform_admin_audit_events.sql
--
-- Creates the append-only audit trail for the separate SaaS platform-admin
-- console. Tenant owner/admin/member roles do not grant platform-admin access.
-- Apply only after 023_create_platform_admin_users.sql.
--
-- This migration is idempotent for the expected clean or already-correct state.
-- It does not repair a pre-existing table with a conflicting definition.

CREATE TABLE IF NOT EXISTS public.platform_admin_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_admin_user_id BIGINT NOT NULL,
    action TEXT NOT NULL,
    resource_type TEXT NOT NULL,
    resource_id TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT platform_admin_audit_events_admin_fkey
        FOREIGN KEY (platform_admin_user_id)
        REFERENCES public.platform_admin_users(id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT platform_admin_audit_events_action_not_blank_check
        CHECK (btrim(action) <> ''),
    CONSTRAINT platform_admin_audit_events_resource_type_not_blank_check
        CHECK (btrim(resource_type) <> ''),
    CONSTRAINT platform_admin_audit_events_metadata_object_check
        CHECK (jsonb_typeof(metadata) = 'object')
);

COMMENT ON TABLE public.platform_admin_audit_events IS
    'Append-only audit trail for the separate SaaS platform-admin console; tenant owner/admin/member roles do not grant access.';

COMMENT ON COLUMN public.platform_admin_audit_events.platform_admin_user_id IS
    'References the platform-admin allowlist row, not a tenant role value.';

COMMENT ON COLUMN public.platform_admin_audit_events.resource_id IS
    'Text representation of a resource identifier so one audit stream can reference BIGINT, UUID, or external identifiers.';

COMMENT ON COLUMN public.platform_admin_audit_events.metadata IS
    'Safe structured context only; never secrets, credentials, access tokens, or complete provider payloads.';

CREATE INDEX IF NOT EXISTS ix_platform_admin_audit_events_admin_created
    ON public.platform_admin_audit_events
    (platform_admin_user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS ix_platform_admin_audit_events_resource_created
    ON public.platform_admin_audit_events
    (resource_type, resource_id, created_at DESC)
    WHERE resource_id IS NOT NULL;

-- ip_address is intentionally omitted until trusted-proxy handling, privacy
-- retention, and the preferred persisted address convention are approved.

-- SECURITY REVIEW REQUIRED BEFORE DEPLOYMENT:
-- The service role receives SELECT and INSERT only. No UPDATE or DELETE grant is
-- made, preserving the application-level append-only posture. Confirm live
-- default privileges, direct grants, and RLS policy requirements in Supabase.
-- This migration does not enable RLS or create policies.
-- Revoke service_role too because GRANT is additive: default ACLs may otherwise
-- defeat the append-only posture by retaining UPDATE or DELETE.
REVOKE ALL ON public.platform_admin_audit_events
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public.platform_admin_audit_events_id_seq
    FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT ON public.platform_admin_audit_events TO service_role;
GRANT USAGE ON SEQUENCE public.platform_admin_audit_events_id_seq TO service_role;
