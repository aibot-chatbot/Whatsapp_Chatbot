-- 072_service_bookings.sql
-- Customer booking / reservation / appointment requests collected in chat, confirmed by staff,
-- and exported as one living CSV per company (app/services/bookings_csv_service.py).
-- Adds table public.service_bookings and the per-chatbot opt-in chatbots.booking_intake_enabled
-- (default false: no chatbot records anything until an admin switches it on).
--
-- Apply BEFORE deploying the code that reads it. Not yet applied anywhere.
-- Safe order: the code treats a missing flag as "off", so a deploy before this migration only
-- disables intake; the Bookings page and the switch need this schema.
--
-- Access: every read and write is by the Flask service (service_role) after it has checked the
-- signed-in user's company. Nothing is reachable by anon or authenticated. The application never
-- deletes a booking (cancel is a status), so service_role gets no DELETE.
--
-- Rows outlive the chat they came from: deleting a conversation or chatbot detaches the booking
-- (SET NULL); only deleting the company removes its bookings.
BEGIN;
SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE public.service_bookings (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id     bigint NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  chatbot_id     bigint REFERENCES public.chatbots(id) ON DELETE SET NULL,
  conversation_id bigint REFERENCES public.conversations(id) ON DELETE SET NULL,
  kind           text NOT NULL DEFAULT 'other'
                 CHECK (kind IN ('booking','reservation','appointment','other')),
  status         text NOT NULL DEFAULT 'requested'
                 CHECK (status IN ('requested','confirmed','cancelled','completed')),
  source         text NOT NULL DEFAULT 'chat' CHECK (source IN ('chat','staff')),
  -- Idempotency: an identical request in the same conversation on the same (Malaysia) day hashes
  -- to the same key, so a replayed webhook or a repeated message cannot create a second open
  -- request. Once a request is cancelled or completed the service salts a fresh key, so asking
  -- again is a new request. A retried model call that words it differently is a new request.
  intake_key     text NOT NULL CHECK (length(intake_key) BETWEEN 1 AND 100),
  customer_name  text CHECK (length(customer_name) <= 120),
  customer_phone text CHECK (length(customer_phone) <= 40),
  customer_ref   text CHECK (length(customer_ref) <= 100),
  channel        text CHECK (length(channel) <= 30),
  service_name   text CHECK (length(service_name) <= 150),
  scheduled_for  timestamptz,
  party_size     integer CHECK (party_size BETWEEN 1 AND 10000),
  notes          text CHECK (length(notes) <= 1000),
  -- Optimistic concurrency: staff edits send the version they saw; a stale write matches no row.
  version        integer NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  confirmed_at   timestamptz,
  cancelled_at   timestamptz,
  CONSTRAINT service_bookings_intake_unique UNIQUE (company_id, intake_key),
  CONSTRAINT service_bookings_confirmed_has_time
    CHECK (status NOT IN ('confirmed','completed') OR confirmed_at IS NOT NULL),
  CONSTRAINT service_bookings_cancelled_has_time
    CHECK (status <> 'cancelled' OR cancelled_at IS NOT NULL)
);

-- Newest first per company: the Bookings list and the CSV export.
CREATE INDEX service_bookings_company_created
  ON public.service_bookings (company_id, created_at DESC, id DESC);
-- The per-conversation hourly request limit, and foreign-key maintenance.
CREATE INDEX service_bookings_conversation
  ON public.service_bookings (conversation_id, created_at) WHERE conversation_id IS NOT NULL;
CREATE INDEX service_bookings_chatbot
  ON public.service_bookings (chatbot_id) WHERE chatbot_id IS NOT NULL;

ALTER TABLE public.service_bookings ENABLE ROW LEVEL SECURITY;

CREATE POLICY service_bookings_service_select
  ON public.service_bookings FOR SELECT TO service_role USING (TRUE);
CREATE POLICY service_bookings_service_insert
  ON public.service_bookings FOR INSERT TO service_role WITH CHECK (TRUE);
CREATE POLICY service_bookings_service_update
  ON public.service_bookings FOR UPDATE TO service_role USING (TRUE) WITH CHECK (TRUE);

REVOKE ALL ON public.service_bookings FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public.service_bookings_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.service_bookings TO service_role;
-- Only the columns staff may change. Ownership and identity (company_id, chatbot_id,
-- conversation_id, intake_key, source, created_at) can never be rewritten, whatever the
-- application does. These are exactly the repository's editable fields plus version/updated_at.
GRANT UPDATE (status, kind, customer_name, service_name, scheduled_for, party_size, notes,
              confirmed_at, cancelled_at, version, updated_at)
  ON public.service_bookings TO service_role;

COMMENT ON TABLE public.service_bookings IS
  'Customer booking requests collected by chatbots. Holds personal data (see column comments). Retention and erasure are not automated.';
COMMENT ON COLUMN public.service_bookings.customer_name  IS 'PII: name the customer gave in chat.';
COMMENT ON COLUMN public.service_bookings.customer_phone IS 'PII: phone number, WhatsApp channels only.';
COMMENT ON COLUMN public.service_bookings.customer_ref   IS 'PII: the channel identifier of the customer (phone number or Telegram id). Never stored for the web widget.';
COMMENT ON COLUMN public.service_bookings.notes          IS 'May contain personal or sensitive free text typed by the customer.';

-- Last on purpose: ALTER TABLE takes an exclusive lock on chatbots, which every inbound message
-- reads. Done last, the lock is held for milliseconds instead of for the whole script.
ALTER TABLE public.chatbots
  ADD COLUMN IF NOT EXISTS booking_intake_enabled boolean NOT NULL DEFAULT false;

COMMIT;
