CREATE TABLE IF NOT EXISTS public.tenant_support_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL
        REFERENCES public.companies(id) ON DELETE RESTRICT,
    requester_user_id BIGINT NOT NULL
        REFERENCES public.users(id) ON DELETE RESTRICT,
    source TEXT NOT NULL DEFAULT 'tenant',
    category TEXT NOT NULL,
    title TEXT NOT NULL,
    redacted_description TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'new',
    priority TEXT NOT NULL DEFAULT 'normal',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    closed_at TIMESTAMPTZ NULL,
    CONSTRAINT tenant_support_requests_source_check
        CHECK (source = 'tenant'),
    CONSTRAINT tenant_support_requests_category_check
        CHECK (category IN (
            'technical', 'account', 'chatbot', 'integration',
            'billing_question', 'ai_credits', 'other'
        )),
    CONSTRAINT tenant_support_requests_status_check
        CHECK (status IN ('new', 'reviewed', 'converted', 'closed')),
    CONSTRAINT tenant_support_requests_priority_check
        CHECK (priority = 'normal'),
    CONSTRAINT tenant_support_requests_title_length_check
        CHECK (char_length(title) BETWEEN 1 AND 160),
    CONSTRAINT tenant_support_requests_description_length_check
        CHECK (char_length(redacted_description) BETWEEN 1 AND 2000),
    CONSTRAINT tenant_support_requests_closed_at_check
        CHECK ((status = 'closed') = (closed_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.tenant_support_request_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL
        REFERENCES public.tenant_support_requests(id) ON DELETE RESTRICT,
    event_type TEXT NOT NULL,
    actor_user_id BIGINT NULL
        REFERENCES public.users(id) ON DELETE RESTRICT,
    actor_platform_admin_user_id BIGINT NULL
        REFERENCES public.platform_admin_users(id) ON DELETE RESTRICT,
    actor_type TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT tenant_support_request_events_type_check
        CHECK (event_type IN ('created', 'reviewed', 'converted', 'closed')),
    CONSTRAINT tenant_support_request_events_actor_type_check
        CHECK (actor_type IN ('tenant', 'platform_admin', 'system')),
    CONSTRAINT tenant_support_request_events_actor_consistency_check
        CHECK (
            (actor_type = 'tenant'
                AND actor_user_id IS NOT NULL
                AND actor_platform_admin_user_id IS NULL)
            OR (actor_type = 'platform_admin'
                AND actor_user_id IS NULL
                AND actor_platform_admin_user_id IS NOT NULL)
            OR (actor_type = 'system'
                AND actor_user_id IS NULL
                AND actor_platform_admin_user_id IS NULL)
        )
);

CREATE TABLE IF NOT EXISTS public.tenant_support_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NULL
        REFERENCES public.tenant_support_requests(id) ON DELETE RESTRICT,
    company_id BIGINT NOT NULL
        REFERENCES public.companies(id) ON DELETE RESTRICT,
    requester_user_id BIGINT NULL
        REFERENCES public.users(id) ON DELETE RESTRICT,
    action TEXT NOT NULL,
    outcome TEXT NOT NULL,
    category TEXT NULL,
    source TEXT NOT NULL DEFAULT 'tenant',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT tenant_support_audit_action_nonblank_check
        CHECK (char_length(btrim(action)) BETWEEN 1 AND 120),
    CONSTRAINT tenant_support_audit_outcome_check
        CHECK (outcome IN ('success', 'denied', 'validation_error', 'rate_limited', 'failed')),
    CONSTRAINT tenant_support_audit_category_check
        CHECK (category IS NULL OR category IN (
            'technical', 'account', 'chatbot', 'integration',
            'billing_question', 'ai_credits', 'other'
        )),
    CONSTRAINT tenant_support_audit_source_check
        CHECK (source = 'tenant')
);

