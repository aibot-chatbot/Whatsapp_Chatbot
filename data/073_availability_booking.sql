-- 073_availability_booking.sql
-- Availability booking (Pro only): per-chatbot packages, weekly hours, one-off slots and
-- closed dates, with seats that cannot be overbooked. Customers book a listed time in chat;
-- the server takes the seat atomically and the model never decides availability.
--
--   booking_packages   what can be booked: name, duration, price rule, seats per time slot
--   booking_schedules  weekly hours per package (Malaysia time) that generate slots
--   booking_closures   dates a chatbot or one package is closed (holidays)
--   booking_slots      bookable times with capacity and booked_seats
--   service_bookings   + package_id, slot_id, seats, price_micro_myr (072's table)
--   chatbots           + booking_auto_confirm (true: a free seat books instantly;
--                        false: the seat is held as 'requested' until staff confirm)
--   subscription_plans feature flag availability_booking, Pro only (068's pattern)
--
-- Apply BEFORE deploying the code that reads it, off-peak: the CREATE TABLEs take SHARE ROW
-- EXCLUSIVE on companies and chatbots (blocks their writes, not reads) until COMMIT.
-- Applied to production 2026-10-04 (Supabase migration 073_availability_booking). Rollback: 073_availability_booking_rollback.sql.
--
-- Seats. booked_seats only moves inside booking_reserve (takes seats) and the
-- service_bookings trigger (gives them back when a slot booking becomes 'cancelled'), both
-- SECURITY DEFINER. service_role can neither INSERT nor UPDATE booked_seats, nor INSERT a
-- booking's slot fields, and CHECK (booked_seats BETWEEN 0 AND capacity) makes an overbooked
-- state unrepresentable. A slot holding a booking cannot be deleted directly (trigger);
-- deleting its chatbot or company still cascades. On Supabase service_role BYPASSES row-level
-- security, so these guards are grants, triggers and CHECKs, never RLS policies.
--
-- Access follows 072: every read and write is by the Flask service (service_role) after it
-- has checked the signed-in user's company. Nothing is reachable by anon or authenticated.
-- Money is integer micro-MYR (RM 1 = 1,000,000), like the rest of billing.
BEGIN;
SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE public.booking_packages (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       bigint NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  chatbot_id       bigint NOT NULL REFERENCES public.chatbots(id) ON DELETE CASCADE,
  name             text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 80),
  description      text CHECK (length(description) <= 500),
  duration_minutes integer NOT NULL CHECK (duration_minutes BETWEEN 5 AND 1440),
  -- none: no price is mentioned; quote: price is given after inspection or consultation.
  price_mode       text NOT NULL DEFAULT 'none'
                   CHECK (price_mode IN ('none','fixed','per_person','quote')),
  price_micro_myr  bigint CHECK (price_micro_myr BETWEEN 0 AND 100000000000),  -- up to RM 100,000
  seats_per_slot   integer NOT NULL DEFAULT 1 CHECK (seats_per_slot BETWEEN 1 AND 1000),
  -- true: a booking takes one seat per person (classes, tables, tours); false: one seat each.
  seats_by_party   boolean NOT NULL DEFAULT false,
  enabled          boolean NOT NULL DEFAULT true,
  sort_order       integer NOT NULL DEFAULT 0,
  version          integer NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT booking_packages_price_needed
    CHECK (price_mode NOT IN ('fixed','per_person') OR price_micro_myr IS NOT NULL),
  -- Lets schedules, closures and slots prove their package belongs to the same tenant.
  CONSTRAINT booking_packages_scope UNIQUE (id, company_id, chatbot_id)
);
CREATE INDEX booking_packages_chatbot ON public.booking_packages (chatbot_id, sort_order, id);
CREATE INDEX booking_packages_company ON public.booking_packages (company_id);

CREATE TABLE public.booking_schedules (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id       bigint NOT NULL,
  chatbot_id       bigint NOT NULL,
  package_id       bigint NOT NULL,
  weekday          smallint NOT NULL CHECK (weekday BETWEEN 1 AND 7),  -- ISO, 1 = Monday, Malaysia time
  start_time       time NOT NULL,
  end_time         time NOT NULL,
  interval_minutes integer NOT NULL CHECK (interval_minutes BETWEEN 5 AND 1440),
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT booking_schedules_order CHECK (end_time > start_time),
  CONSTRAINT booking_schedules_package FOREIGN KEY (package_id, company_id, chatbot_id)
    REFERENCES public.booking_packages (id, company_id, chatbot_id) ON DELETE CASCADE
);
CREATE INDEX booking_schedules_package ON public.booking_schedules (package_id);

CREATE TABLE public.booking_closures (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  bigint NOT NULL,
  chatbot_id  bigint NOT NULL,
  package_id  bigint,  -- NULL closes every package of the chatbot that day
  closed_on   date NOT NULL,  -- Malaysia date
  reason      text CHECK (length(reason) <= 120),
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT booking_closures_once UNIQUE NULLS NOT DISTINCT (chatbot_id, package_id, closed_on),
  CONSTRAINT booking_closures_chatbot FOREIGN KEY (chatbot_id)
    REFERENCES public.chatbots (id) ON DELETE CASCADE,
  CONSTRAINT booking_closures_package FOREIGN KEY (package_id, company_id, chatbot_id)
    REFERENCES public.booking_packages (id, company_id, chatbot_id) ON DELETE CASCADE
);
CREATE INDEX booking_closures_package ON public.booking_closures (package_id) WHERE package_id IS NOT NULL;

CREATE TABLE public.booking_slots (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id   bigint NOT NULL,
  chatbot_id   bigint NOT NULL,
  package_id   bigint NOT NULL,
  starts_at    timestamptz NOT NULL,
  ends_at      timestamptz NOT NULL,
  capacity     integer NOT NULL CHECK (capacity BETWEEN 1 AND 1000),
  booked_seats integer NOT NULL DEFAULT 0,
  status       text NOT NULL DEFAULT 'open' CHECK (status IN ('open','closed')),
  source       text NOT NULL DEFAULT 'schedule' CHECK (source IN ('schedule','one_off')),
  version      integer NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT booking_slots_order CHECK (ends_at > starts_at),
  -- The no-overbooking rule. Lowering capacity below the booked seats also fails here.
  CONSTRAINT booking_slots_seats CHECK (booked_seats BETWEEN 0 AND capacity),
  CONSTRAINT booking_slots_once UNIQUE (package_id, starts_at),
  CONSTRAINT booking_slots_package FOREIGN KEY (package_id, company_id, chatbot_id)
    REFERENCES public.booking_packages (id, company_id, chatbot_id) ON DELETE CASCADE
);
-- The chat prompt and the owner list: open future times per chatbot.
CREATE INDEX booking_slots_open ON public.booking_slots (chatbot_id, starts_at) WHERE status = 'open';

-- A direct DELETE (slot regeneration) may remove a future slot, never one that holds a
-- booking. Deleting the chatbot or company cascades here at trigger depth > 1 and is allowed.
CREATE OR REPLACE FUNCTION public.booking_slots_keep_booked()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF OLD.booked_seats > 0 AND pg_trigger_depth() = 1 THEN
    RAISE EXCEPTION 'booking_slot_has_bookings' USING ERRCODE = '23503';
  END IF;
  RETURN OLD;
END
$$;
CREATE TRIGGER booking_slots_keep_booked BEFORE DELETE ON public.booking_slots
  FOR EACH ROW EXECUTE FUNCTION public.booking_slots_keep_booked();

ALTER TABLE public.booking_packages  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.booking_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.booking_closures  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.booking_slots     ENABLE ROW LEVEL SECURITY;

CREATE POLICY booking_packages_service ON public.booking_packages
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);
CREATE POLICY booking_schedules_service ON public.booking_schedules
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);
CREATE POLICY booking_closures_service ON public.booking_closures
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);
CREATE POLICY booking_slots_service ON public.booking_slots
  FOR ALL TO service_role USING (TRUE) WITH CHECK (TRUE);

REVOKE ALL ON public.booking_packages, public.booking_schedules, public.booking_closures,
              public.booking_slots FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public.booking_packages_id_seq, public.booking_schedules_id_seq,
                       public.booking_closures_id_seq, public.booking_slots_id_seq
  FROM PUBLIC, anon, authenticated;
-- Packages are switched off, never deleted, so past bookings keep their package.
GRANT SELECT, INSERT ON public.booking_packages TO service_role;
GRANT UPDATE (name, description, duration_minutes, price_mode, price_micro_myr, seats_per_slot,
              seats_by_party, enabled, sort_order, version, updated_at)
  ON public.booking_packages TO service_role;
-- Weekly hours are replaced as a set (delete + insert).
GRANT SELECT, INSERT, DELETE ON public.booking_schedules TO service_role;
GRANT SELECT, INSERT, DELETE ON public.booking_closures TO service_role;
-- booked_seats is deliberately neither insertable nor updatable here (it starts at 0).
GRANT SELECT, DELETE ON public.booking_slots TO service_role;
GRANT INSERT (company_id, chatbot_id, package_id, starts_at, ends_at, capacity, status, source)
  ON public.booking_slots TO service_role;
GRANT UPDATE (capacity, status, version, updated_at) ON public.booking_slots TO service_role;

-- Take seats for one chat booking. Locks the slot, so two customers can never share the last
-- seat. Returns {"outcome": confirmed | held | replayed | full | unavailable, ...}. A replay of
-- the same request (same intake_key) returns the existing booking and takes no seat; the check
-- runs after the slot lock, so even two identical requests in the same instant book once.
-- A closed date is re-checked here because closing a day is two separate writes in the app.
CREATE OR REPLACE FUNCTION public.booking_reserve(
  p_company_id bigint, p_chatbot_id bigint, p_slot_id bigint, p_party_size integer,
  p_confirm boolean, p_booking jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  slot     public.booking_slots;
  pkg      public.booking_packages;
  existing public.service_bookings;
  created  public.service_bookings;
  v_key    text := p_booking ->> 'intake_key';
  v_seats  integer;
BEGIN
  IF p_party_size IS NULL OR p_party_size NOT BETWEEN 1 AND 1000 THEN
    RAISE EXCEPTION 'booking_invalid_party_size' USING ERRCODE = '22023';
  END IF;
  IF v_key IS NULL OR length(v_key) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'booking_invalid_key' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO slot FROM public.booking_slots
   WHERE id = p_slot_id AND company_id = p_company_id AND chatbot_id = p_chatbot_id
   FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('outcome', 'unavailable');
  END IF;

  SELECT * INTO existing FROM public.service_bookings
   WHERE company_id = p_company_id AND intake_key = v_key;
  IF FOUND THEN
    RETURN jsonb_build_object('outcome', 'replayed', 'booking', to_jsonb(existing));
  END IF;

  SELECT * INTO pkg FROM public.booking_packages
   WHERE id = slot.package_id AND company_id = p_company_id AND chatbot_id = p_chatbot_id;
  IF NOT FOUND OR NOT pkg.enabled OR slot.status <> 'open' OR slot.starts_at <= now()
     OR EXISTS (SELECT 1 FROM public.booking_closures c
                 WHERE c.chatbot_id = p_chatbot_id AND (c.package_id IS NULL OR c.package_id = pkg.id)
                   AND c.closed_on = (slot.starts_at AT TIME ZONE 'Asia/Kuala_Lumpur')::date) THEN
    RETURN jsonb_build_object('outcome', 'unavailable');
  END IF;

  v_seats := CASE WHEN pkg.seats_by_party THEN p_party_size ELSE 1 END;
  IF slot.booked_seats + v_seats > slot.capacity THEN
    RETURN jsonb_build_object('outcome', 'full', 'seats_left', slot.capacity - slot.booked_seats);
  END IF;

  INSERT INTO public.service_bookings (
    company_id, chatbot_id, conversation_id, kind, status, source, intake_key,
    customer_name, customer_phone, customer_ref, channel, service_name, scheduled_for,
    party_size, notes, confirmed_at, package_id, slot_id, seats, price_micro_myr)
  VALUES (
    p_company_id, p_chatbot_id, (p_booking ->> 'conversation_id')::bigint,
    COALESCE(p_booking ->> 'kind', 'booking'),
    CASE WHEN p_confirm THEN 'confirmed' ELSE 'requested' END, 'chat', v_key,
    p_booking ->> 'customer_name', p_booking ->> 'customer_phone', p_booking ->> 'customer_ref',
    p_booking ->> 'channel', pkg.name, slot.starts_at, p_party_size, p_booking ->> 'notes',
    CASE WHEN p_confirm THEN now() END, pkg.id, slot.id, v_seats,
    CASE pkg.price_mode WHEN 'fixed' THEN pkg.price_micro_myr
                        WHEN 'per_person' THEN pkg.price_micro_myr * p_party_size END)
  RETURNING * INTO created;

  UPDATE public.booking_slots
     SET booked_seats = booked_seats + v_seats, version = version + 1, updated_at = now()
   WHERE id = slot.id;

  RETURN jsonb_build_object('outcome', CASE WHEN p_confirm THEN 'confirmed' ELSE 'held' END,
                            'booking', to_jsonb(created));
END
$$;

REVOKE ALL ON FUNCTION public.booking_reserve(bigint, bigint, bigint, integer, boolean, jsonb)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.booking_reserve(bigint, bigint, bigint, integer, boolean, jsonb)
  TO service_role;

-- Keeps a slot booking's seats honest on every staff update path (072's PATCH included):
-- live -> cancelled gives the seats back; a cancelled or completed slot booking cannot come
-- back to life; its time and party size are fixed (cancel and book again instead). slot_id,
-- package_id and seats are not in service_role's UPDATE grant, so only a cascade (deleting the
-- slot's chatbot or company) can change them, and that detaches the booking (SET NULL).
-- Lock order (booking row, then slot) cannot deadlock with booking_reserve, which locks the
-- slot and only inserts a new booking row.
CREATE OR REPLACE FUNCTION public.service_bookings_keep_seats()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF OLD.slot_id IS NULL OR NEW.slot_id IS NULL THEN
    RETURN NEW;
  END IF;
  IF NEW.party_size IS DISTINCT FROM OLD.party_size OR NEW.scheduled_for IS DISTINCT FROM OLD.scheduled_for THEN
    RAISE EXCEPTION 'booking_slot_fields_fixed' USING ERRCODE = '23514';
  END IF;
  IF OLD.status IN ('cancelled', 'completed') AND NEW.status IS DISTINCT FROM OLD.status THEN
    RAISE EXCEPTION 'booking_slot_finished' USING ERRCODE = '23514';
  END IF;
  IF OLD.status IN ('requested', 'confirmed') AND NEW.status = 'cancelled' THEN
    -- A shortfall here is a bug, so it fails loudly on the seats CHECK instead of hiding it.
    UPDATE public.booking_slots
       SET booked_seats = booked_seats - OLD.seats, version = version + 1, updated_at = now()
     WHERE id = OLD.slot_id;
  END IF;
  RETURN NEW;
END
$$;
REVOKE ALL ON FUNCTION public.service_bookings_keep_seats() FROM PUBLIC, anon, authenticated;

COMMENT ON TABLE public.booking_packages IS 'Bookable packages per chatbot (availability booking, Pro).';
COMMENT ON TABLE public.booking_slots IS 'Bookable times. booked_seats moves only through booking_reserve and the service_bookings_keep_seats trigger.';

-- === Plan feature flag: availability_booking is Pro only (068's pattern) ===
--                          free   essential   advanced   pro
--   availability_booking   false    false       false     true
-- One literal per plan, so tests/test_plan_feature_gating.py can replay the matrix.
UPDATE public.subscription_plans
   SET feature_flags = COALESCE(feature_flags, '{}'::jsonb) || jsonb_build_object('availability_booking', false)
 WHERE LOWER(code) = 'free';
UPDATE public.subscription_plans
   SET feature_flags = COALESCE(feature_flags, '{}'::jsonb) || jsonb_build_object('availability_booking', false)
 WHERE LOWER(code) = 'essential';
UPDATE public.subscription_plans
   SET feature_flags = COALESCE(feature_flags, '{}'::jsonb) || jsonb_build_object('availability_booking', false)
 WHERE LOWER(code) = 'advanced';
UPDATE public.subscription_plans
   SET feature_flags = COALESCE(feature_flags, '{}'::jsonb) || jsonb_build_object('availability_booking', true)
 WHERE LOWER(code) = 'pro';
-- Every other plan code fails closed. "code IS NULL OR" is load-bearing (see 068).
UPDATE public.subscription_plans
   SET feature_flags = COALESCE(feature_flags, '{}'::jsonb) || jsonb_build_object('availability_booking', false)
 WHERE code IS NULL OR LOWER(code) NOT IN ('free', 'essential', 'advanced', 'pro');

DO $$
DECLARE
  offenders text;
BEGIN
  SELECT string_agg(COALESCE(p.code, '(null code)'), ', ')
    INTO offenders
    FROM public.subscription_plans p
   WHERE jsonb_typeof(COALESCE(p.feature_flags, '{}'::jsonb) -> 'availability_booking') IS DISTINCT FROM 'boolean'
      OR ((p.feature_flags -> 'availability_booking') = 'true'::jsonb AND LOWER(COALESCE(p.code, '')) <> 'pro');
  IF offenders IS NOT NULL THEN
    RAISE EXCEPTION '073 aborted: availability_booking is missing or granted outside Pro: %', offenders;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.subscription_plans WHERE LOWER(code) = 'pro') THEN
    RAISE EXCEPTION '073 aborted: no pro plan to grant availability_booking to';
  END IF;
END
$$;

-- Last on purpose (see 072): these ALTERs take ACCESS EXCLUSIVE locks on tables every inbound
-- message touches, so they are held for milliseconds instead of for the whole script.
ALTER TABLE public.service_bookings
  ADD COLUMN package_id      bigint REFERENCES public.booking_packages (id) ON DELETE SET NULL,
  ADD COLUMN slot_id         bigint REFERENCES public.booking_slots (id) ON DELETE SET NULL,
  ADD COLUMN seats           integer CHECK (seats BETWEEN 1 AND 1000),
  ADD COLUMN price_micro_myr bigint CHECK (price_micro_myr >= 0);
CREATE INDEX service_bookings_slot ON public.service_bookings (slot_id) WHERE slot_id IS NOT NULL;
CREATE INDEX service_bookings_package ON public.service_bookings (package_id) WHERE package_id IS NOT NULL;
CREATE TRIGGER service_bookings_keep_seats BEFORE UPDATE ON public.service_bookings
  FOR EACH ROW EXECUTE FUNCTION public.service_bookings_keep_seats();
-- 072 granted INSERT on the whole table, which would let a plain insert claim a slot without
-- taking its seat. From now on only booking_reserve sets package_id, slot_id, seats and price.
REVOKE INSERT ON public.service_bookings FROM service_role;
GRANT INSERT (company_id, chatbot_id, conversation_id, kind, status, source, intake_key,
              customer_name, customer_phone, customer_ref, channel, service_name, scheduled_for,
              party_size, notes, confirmed_at, cancelled_at)
  ON public.service_bookings TO service_role;

ALTER TABLE public.chatbots
  ADD COLUMN IF NOT EXISTS booking_auto_confirm boolean NOT NULL DEFAULT true;

COMMIT;
