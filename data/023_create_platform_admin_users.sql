-- 023_create_platform_admin_users.sql
--
-- Creates the separate SaaS-operator allowlist used for platform-admin access.
-- Platform-admin authorization must never be inferred from the tenant-scoped
-- public.users.role values owner/admin/member, and this migration does not
-- modify that column or tenant role behavior.
--
-- This migration is idempotent for the expected clean or already-correct state.
-- It does not repair a pre-existing table with a conflicting definition.

CREATE TABLE IF NOT EXISTS public.platform_admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by_user_id BIGINT,

    CONSTRAINT platform_admin_users_user_id_key UNIQUE (user_id),
    CONSTRAINT platform_admin_users_user_id_fkey
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,
    CONSTRAINT platform_admin_users_created_by_user_id_fkey
        FOREIGN KEY (created_by_user_id)
        REFERENCES public.users(id)
        ON UPDATE RESTRICT
        ON DELETE SET NULL
);

COMMENT ON TABLE public.platform_admin_users IS
    'SaaS-operator allowlist. Platform-admin authorization is separate from tenant users.role values owner/admin/member.';

COMMENT ON COLUMN public.platform_admin_users.user_id IS
    'Existing application user granted separate platform-admin eligibility; tenant role alone never grants platform access.';

COMMENT ON COLUMN public.platform_admin_users.is_active IS
    'Revocation flag. Deactivate platform access instead of deleting this row so audit attribution remains intact.';

COMMENT ON COLUMN public.platform_admin_users.updated_at IS
    'Last application-managed update time. No timestamp trigger is installed; application code must set updated_at explicitly.';

COMMENT ON COLUMN public.platform_admin_users.created_by_user_id IS
    'Application user that provisioned this mapping, when known. Nullable for the bootstrap administrator.';

-- UNIQUE (user_id) supplies the platform-access lookup index. An is_active-only
-- index is intentionally omitted because this allowlist should remain small.

-- SECURITY REVIEW REQUIRED BEFORE DEPLOYMENT:
-- These grants implement the intended service-role-only application posture.
-- Confirm live default privileges, direct grants, and RLS policy requirements
-- in Supabase before applying this migration. This migration does not enable
-- RLS or create policies.
-- Revoke service_role too because GRANT is additive: default ACLs may otherwise
-- leave DELETE or other unintended direct privileges in place.
REVOKE ALL ON public.platform_admin_users
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public.platform_admin_users_id_seq
    FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE ON public.platform_admin_users TO service_role;
GRANT USAGE ON SEQUENCE public.platform_admin_users_id_seq TO service_role;
