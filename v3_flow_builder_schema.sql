-- V3 Flow Builder Schema Updates

-- 1. Upgrade 'flows' table to support Draft vs Published states
ALTER TABLE public.flows 
ADD COLUMN IF NOT EXISTS draft_data jsonb,
ADD COLUMN IF NOT EXISTS published_data jsonb,
ADD COLUMN IF NOT EXISTS published_at timestamp with time zone;

-- Migrate existing flow_data to draft_data and published_data
UPDATE public.flows 
SET draft_data = flow_data, published_data = flow_data 
WHERE draft_data IS NULL;

-- 2. Upgrade 'conversations' table to support Flow Variables (Memory)
ALTER TABLE public.conversations
ADD COLUMN IF NOT EXISTS workflow_variables jsonb DEFAULT '{}'::jsonb;

-- 3. Create 'execution_logs' table for Analytics and Debugging
CREATE TABLE IF NOT EXISTS public.execution_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint REFERENCES public.companies(id) ON DELETE CASCADE,
    chatbot_id bigint REFERENCES public.chatbots(id) ON DELETE CASCADE,
    conversation_id bigint REFERENCES public.conversations(id) ON DELETE CASCADE,
    flow_id bigint REFERENCES public.flows(id) ON DELETE CASCADE,
    node_id text NOT NULL,
    node_type text NOT NULL,
    status text NOT NULL DEFAULT 'success', -- 'success', 'failed', 'waiting'
    error_message text,
    executed_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Grant permissions to backend
GRANT ALL ON TABLE public.execution_logs TO authenticated;
GRANT ALL ON TABLE public.execution_logs TO service_role;
GRANT ALL ON TABLE public.execution_logs TO anon;
